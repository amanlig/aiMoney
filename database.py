"""Application database boundary. DATABASE_URL selects PostgreSQL.

Explicit non-default SQLite paths remain supported for isolated fixtures and
read-only legacy exports; a configured PostgreSQL failure never falls back.
"""
import os
from pathlib import Path
import re
import sqlite3
import psycopg
from psycopg.rows import dict_row

DB = Path(__file__).resolve().parent / 'data/fx-samples.sqlite3'
ERRORS = (sqlite3.Error, psycopg.Error)
INTEGRITY_ERRORS = (sqlite3.IntegrityError, psycopg.IntegrityError)


class Connection:
    def __init__(self, raw, postgres):
        self.raw, self.postgres = raw, postgres

    def execute(self, sql, params=()):
        if self.postgres:
            # Only application-owned statements pass through this boundary.
            if sql.lstrip().upper().startswith('CREATE TABLE'):
                sql = sql.replace('INTEGER PRIMARY KEY', 'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY')
                sql = re.sub(r'\bREAL\b', 'DOUBLE PRECISION', sql)
            sql = sql.replace('?', '%s')
        return self.raw.execute(sql, params)

    def insert_id(self, sql, params):
        if self.postgres:
            return self.execute(sql + ' RETURNING id', params).fetchone()['id']
        return self.execute(sql, params).lastrowid

    def table_exists(self, name):
        if self.postgres:
            return bool(self.execute("SELECT 1 FROM information_schema.tables WHERE table_schema=current_schema() AND table_name=?", (name,)).fetchone())
        return bool(self.execute("SELECT 1 FROM sqlite_master WHERE type='table' AND name=?", (name,)).fetchone())

    def __enter__(self):
        return self

    def __exit__(self, kind, value, traceback):
        try:
            if kind is None:
                self.raw.commit()
            else:
                self.raw.rollback()
        finally:
            self.raw.close()


def connect(path=DB, *, readonly=False, url=None):
    target = url or (os.environ.get('DATABASE_URL') if Path(path) == DB else None)
    if target:
        raw = psycopg.connect(target, row_factory=dict_row, connect_timeout=10)
        if readonly:
            raw.execute('SET TRANSACTION READ ONLY')
        return Connection(raw, True)
    path = Path(path)
    if readonly:
        raw = sqlite3.connect(path.resolve().as_uri() + '?mode=ro', uri=True, timeout=10)
    else:
        path.parent.mkdir(parents=True, exist_ok=True)
        raw = sqlite3.connect(path, timeout=10)
    raw.row_factory = sqlite3.Row
    return Connection(raw, False)
